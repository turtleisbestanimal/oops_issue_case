import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
test('database permissions, validation, revision conflict, trash and purge',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql as $$select nullif(current_setting('test.uid',true),'')::uuid$$;grant usage on schema auth to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;`);
 await db.exec(await readFile('supabase/schema.sql','utf8'));await db.exec(await readFile('supabase/seed.sql','utf8'));
 const user='00000000-0000-0000-0000-000000000001';await db.exec(`insert into auth.users values('${user}');insert into public.oops_admins values('${user}');`);
 const state=(await db.query('select state from public.oops_workspace')).rows[0].state;
 assert.equal(Object.keys(state.cases).length,123);
 await db.exec('set role anon');assert.equal((await db.query('select revision from public.oops_workspace')).rows[0].revision,1);
 await assert.rejects(db.query('update public.oops_workspace set revision=5'),/permission denied/);
 await assert.rejects(db.query('select public.oops_save_state(1,$1)',[state]),/permission denied/);
 await db.exec('set role authenticated');await assert.rejects(db.query('select public.oops_save_state(1,$1)',[state]),/OOPS_FORBIDDEN/);
 await db.query("select set_config('test.uid',$1,false)",[user]);
 state.cases['OOPS-006'].elements[0]='테스트 수정';
 assert.equal((await db.query('select public.oops_save_state(1,$1) revision',[state])).rows[0].revision,2);
 await assert.rejects(db.query('select public.oops_save_state(1,$1)',[state]),/OOPS_CONFLICT/);
 const invalid=structuredClone(state);invalid.cases['OOPS-006'].elements=[];
 await assert.rejects(db.query('select public.oops_save_state(2,$1)',[invalid]),/OOPS_INVALID_ELEMENTS/);
 const purge=structuredClone(state);purge.purged['OOPS-006']=new Date().toISOString();delete purge.cases['OOPS-006'];
 await assert.rejects(db.query('select public.oops_save_state(2,$1)',[purge]),/OOPS_TRASH_FIRST/);
 state.cases['OOPS-006'].deletedAt=new Date().toISOString();await db.query('select public.oops_save_state(2,$1)',[state]);
 state.purged['OOPS-006']=new Date().toISOString();delete state.cases['OOPS-006'];await db.query('select public.oops_save_state(3,$1)',[state]);
 const resurrect=structuredClone(state);delete resurrect.purged['OOPS-006'];resurrect.cases['OOPS-006']=purge.cases['OOPS-009'];
 await assert.rejects(db.query('select public.oops_save_state(4,$1)',[resurrect]),/OOPS_PURGED_IMMUTABLE/);
 await db.exec('reset role');await db.exec(await readFile('supabase/seed.sql','utf8'));assert.equal((await db.query('select revision from public.oops_workspace')).rows[0].revision,4);
 await db.close();
});
